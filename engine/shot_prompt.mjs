// Промпт опорного кадра — один источник правды.
// Им пользуются gemini_shots.mjs (генерация/показ) и build_manual_shots.mjs
// (сборка рабочего документа для ручной генерации владельцем).
//
// Структура переписана 29.08.2026 по ресерчу
// (docs/research-gemini-image-prompting-29-08.md). Что изменилось и почему:
//
// 1. Промпт начинается с сильного глагола и с главного в кадре. Гайд Google
//    прямо требует «start a prompt with a strong verb that tells the model
//    the primary operation». Раньше действие тонуло в середине, после
//    четырёх абзацев паспортов, — до него внимание модели не доходило.
// 2. Каждому персонажу явно назван НОМЕР его референса и добавлен якорь
//    «тот же самый человек, что на референсе N». Это самая надёжная формула
//    удержания идентичности.
// 3. Листов персонажей подаём до пяти (было три): Gemini 3 Pro Image держит
//    консистентность пяти персонажей одновременно. Из-за старого лимита в
//    три листа в сценах на 5–6 человек путались лица.
// 4. Кто идёт без листа — сказано прямо, чтобы это было видно при проверке
//    кадра.
// 5. Шесть блоков правил сжаты в два. Длинный хвост инструкций конкурирует
//    с картинками-референсами за внимание модели.
// 6. Одежда отдельно оговорена для дальних фигур: «outfit reinterpretation
//    at distance» — известная поломка, из-за неё фоновая фигура на втором
//    плане оказывалась в чужой одежде.
// 7. Формулировки только позитивные: негативных промптов у Gemini Image нет,
//    «без дыма» модель читает как упоминание дыма.

export const MAX_SHEETS = 5; // листов персонажей на запрос (Pro держит пять)
export const MAX_REFS = 6;   // всего изображений: пять листов + фон

// У кого референс — одиночная фигура в полный рост, а не лист с позами
// (описание роли файла должно совпадать с файлом: промпт не должен звать
// «листом в нескольких позах» картинку с одной позой). Когда для персонажа
// появится настоящий лист поз — файл в gemini_refs.json меняется, а имя
// отсюда вычёркивается.
export const SINGLE_POSE = new Set(["roksana", "nastya", "igor"]);

const NUM = ["", "1 ЧЕЛОВЕК", "2 ЧЕЛОВЕКА", "3 ЧЕЛОВЕКА", "4 ЧЕЛОВЕКА",
  "5 ЧЕЛОВЕК", "6 ЧЕЛОВЕК", "7 ЧЕЛОВЕК"];

/** Персонажи сцены, которым достанется лист референса (в порядке подачи). */
export function sheetChars(sc, REFS) {
  return (sc.chars ?? []).filter((c) => REFS[c]).slice(0, MAX_SHEETS);
}

/** Файлы-вложения к промпту, строго в порядке номеров референсов. */
export function refFiles(j, sc, REFS) {
  const files = sheetChars(sc, REFS).map((c) => REFS[c][0]);
  files.push(j.backgrounds[sc.bg].file);
  return files.slice(0, MAX_REFS);
}

export function buildPrompt(j, sc, REFS) {
  const chars = sc.chars ?? [];
  const sheets = sheetChars(sc, REFS);
  const bg = j.backgrounds[sc.bg];
  const refNo = new Map(sheets.map((c, i) => [c, i + 1]));
  const L = [];

  // 1. Операция и главное в кадре — первым, сильным глаголом.
  L.push(
    "Нарисуй один горизонтальный кадр 16:9 для обучающего рисованного видео.",
  );
  L.push(`ГЛАВНОЕ В КАДРЕ: ${sc.img}`);

  // 2. Роли референсов. Листы персонажей первыми, фон последним.
  const roles = [];
  for (const c of sheets) {
    const kind = SINGLE_POSE.has(c)
      ? `референс персонажа «${j.characters[c].name}»: один человек в полный рост`
      : `лист персонажа «${j.characters[c].name}»: один и тот же человек ` +
        `в нескольких позах`;
    roles.push(
      `${refNo.get(c)} — ${kind}, справочник внешности, а не сцена. ` +
      `В кадре это тот же самый человек: то же лицо, та же причёска, та же одежда.`,
    );
  }
  roles.push(
    `${sheets.length + 1} — фон «${bg.name}»: комната этого кадра. ` +
    `Мебель и её расстановка берутся отсюда.`,
  );
  L.push("РЕФЕРЕНСЫ (роль каждого файла):\n" + roles.join("\n"));

  // 3. Состав — только счёт и имена. Раскладку по кадру задаёт текст действия
  //    (sc.img): автоматическая карта «левее/правее» строилась из порядка chars
  //    и в части сцен противоречила мизансцене — противоречие хуже отсутствия
  //    карты (ревью 30.08).
  if (chars.length) {
    const names = chars.map((c) => j.characters[c].name);
    L.push(
      `СОСТАВ: в кадре ровно ${NUM[chars.length] ?? chars.length + " ЧЕЛОВЕК"}, ` +
      `и в комнате больше никого нет: ${names.join(", ")}. ` +
      `Каждый нарисован ровно один раз, каждый стоит или сидит там, ` +
      `где сказано в «ГЛАВНОЕ В КАДРЕ».`,
    );
    // 4. Кто есть кто — с номером листа. Паспорт в компиляте уже начинается
    //    с имени, поэтому имя не дублируем.
    const who = chars.map((c) => {
      const src = refNo.has(c)
        ? `референс ${refNo.get(c)}`
        : "листа нет, рисуется по описанию";
      return `— (${src}) ${j.characters[c].passport}.`;
    });
    L.push("КТО ЕСТЬ КТО:\n" + who.join("\n"));
  } else {
    L.push(
      "СОСТАВ: в кадре нет людей — только комната и предметы. " +
      "Если по действию нужны руки, они принадлежат человеку, целиком " +
      "видимому в кадре.",
    );
  }

  // 5. Комната и стиль — дословно и одинаково во всей серии.
  L.push(
    `КОМНАТА: в точности как на референсе фона — та же мебель на тех же местах ` +
    `и только она; ${bg.desc}. Персонажи стоят на полу или сидят на мебели ` +
    `по её назначению, свет и цветовая температура едины с фоном, ` +
    `тени падают в ту же сторону, что на фоне.`,
  );
  L.push(`СТИЛЬ: ${j.style}`);

  // 6. Правила кадра — сжато, всё позитивно.
  L.push(
    "ПРАВИЛА КАДРА: каждый сидящий персонаж полностью опирается на своё " +
    "сиденье — таз на сиденье, спина у спинки, обе ступни на полу, между " +
    "телом и мебелью нет просвета; каждый стоящий стоит обеими подошвами на " +
    "полу, ниже уровня столешниц, и пол под ним виден. У каждого человека " +
    "ровно две руки, две кисти и две ноги; кисти анатомичные, по пять " +
    "пальцев; каждая кисть в кадре принадлежит человеку, целиком видимому в " +
    "кадре. Мебель — только та, что на референсе фона, и на своих местах; " +
    "силуэт человека и силуэт мебели не пересекаются. Одежда каждого " +
    "персонажа — его собственная с его листа и остаётся на нём; это верно и " +
    "для фигур в глубине кадра: там та же одежда, только мельче. Линия " +
    "горизонта одна на весь кадр, рост взрослого человека соразмерен дверям " +
    "и мебели рядом, ступни всех людей лежат на одной плоскости пола.",
  );
  L.push(
    "ДЕТАЛИ: надписи на досках, экранах, бумагах и обложках выглядят как " +
    "нечитаемые акварельные штрихи. Рты закрыты, лица спокойные. Воздух в " +
    "комнате чистый и прозрачный. Фигуры целиком помещаются в кадр, никого " +
    "не срезает краем.",
  );

  return L.join("\n\n");
}
