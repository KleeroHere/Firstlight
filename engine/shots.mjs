// Раскадровка сцены: сколько планов и сколько клипов в каждом.
//
// ПОЧЕМУ ЭТОТ ФАЙЛ ВООБЩЕ ЕСТЬ
//
// Сцена в сценарии длится тридцать секунд. Wan отдаёт 5,06 с за раз
// (81 кадр при 16 fps). Значит сцена — это не один клип, а цепочка:
// каждый следующий клип стартует с последнего кадра предыдущего.
//
// Цепочка не бесконечна. Каждый прогон через VAE теряет немного
// резкости и немного лица, и после трёх звеньев (около пятнадцати
// секунд) герой начинает плыть. Поэтому длинная сцена режется на
// ПЛАНЫ: план — три клипа максимум, дальше монтажная склейка на новый
// сгенерированный кадр. Это не компромисс, а нормальный монтаж:
// тридцать секунд одним куском без склейки не снимает никто.
//
// Один источник правды для трёх скриптов: comfy_frames (сколько
// опорных кадров рисовать), comfy_batch (сколько клипов гнать),
// verify_clips (что считать сценой при приёмке).

export const CLIP_SEC = 5.06;      // 81 кадр при 16 fps
export const MAX_CHAIN = 3;        // звеньев в одном плане до склейки
export const TAIL_SLACK = 1.2;     // недобор, который сборщик закрывает стоп-кадром

// Про TAIL_SLACK. Сцена на 31 с при честном округлении вверх требует
// семь звеньев (35,4 с) — лишняя минута аренды ради четырёх секунд,
// которые всё равно обрежутся. Сборщик умеет добирать хвост
// клонированным кадром; полторы секунды такого хвоста глазом
// не ловятся. Поэтому округляем вверх не от длины сцены, а от длины
// минус этот допуск: 143 сцены из 177 ложатся ровно, а тринадцать
// тридцатиоднасекундных перестают стоить лишнего звена каждая.

export function sceneSeconds(sc) {
  return Math.max(0, Number(sc.t?.[1] ?? 0) - Number(sc.t?.[0] ?? 0));
}

// Возвращает [{ k, clips, sec }] — планы сцены по порядку.
export function shotPlan(sc, { clipSec = CLIP_SEC, maxChain = MAX_CHAIN } = {}) {
  const dur = sceneSeconds(sc);
  if (dur <= 0) return [];
  const clips = Math.max(1, Math.ceil((dur - TAIL_SLACK) / clipSec));
  const shots = Math.ceil(clips / maxChain);
  const base = Math.floor(clips / shots);
  const extra = clips % shots;              // первые планы длиннее на клип
  const plan = [];
  for (let k = 1; k <= shots; k++) {
    const n = base + (k <= extra ? 1 : 0);
    plan.push({ k, clips: n, sec: Number((n * clipSec).toFixed(2)) });
  }
  return plan;
}

// Имена файлов. Держим их здесь, чтобы три скрипта не разошлись.
export const frameName = (sceneId, k) => `${sceneId}_sh${k}_frame.png`;
export const clipName = (sceneId, k, j) => `${sceneId}_sh${k}_c${j}.mp4`;
export const sceneTake = (sceneId, take = 1) => `${sceneId}_take${take}.mp4`;

// Подсказка по крупности для второго и следующих планов. Первый план
// берёт крупность из самого сценария (в sc.img она обычно указана).
const FRAMING = [
  null,
  "Ракурс сменился: средний план, камера ближе. Те же люди, та же комната, та же одежда, тот же момент.",
  "Ракурс сменился: крупный план лиц. Те же люди, та же комната, та же одежда, тот же момент.",
  "Ракурс сменился: общий план сбоку. Те же люди, та же комната, та же одежда, тот же момент.",
];
export function framingHint(k) {
  return FRAMING[(k - 1) % FRAMING.length];
}
